def plot_quant_over_time(ax, 
                         data_name, normalise_per_100k = True,
                         algs=None, show_quartiles = False, show_normal_CI = False,
                         alg_colors=algorithm_colors, alg_labels=algorithm_labels,
                         burnin_timesteps=4*20, burnout_timesteps = 4*5, smoothing_kernel=4):
    """
    ax: matplotlib.pyplot Axis object on which to plot
    data_name: what is to be plotted on the y axis (data_name<-data_names)
    normalise_per_100k: whether to plot all data per 100k members of the population from which data_name is taken (all agents, all vaccinated agents, or all unvaccinated agents)

    algs: the algorithms to be plotted (algs is to be a subset of algorithms)
    show_quartiles: if True, plots median curve at each timepoint bounded by LQ and UQ. 
    show_normal_CI: If True, plots mean and the t-test confidence interval around the mean.
        NOTE: show_quartiles and show_normal_CI cannot simultaneously be true

    alg_colors (dict): dictionary mapping elements of algs to colors for their matplotlib plotting. If None, sticks with default matplotlib colors
    alg_labels (dict): dictionary mapping elements of algs to names for them for thier matplotlib plotting. If left as default, sticks with internal names as in algs

    burnin_timesteps: the number of timesteps to ignore at the start of the plot, for burnin
    burnout_timesteps: the number of timesteps to ignore at the end of the plot, s.t. post-moving-average-smoothing we don't get an incorrect dropoff at the end of the plot (if 0, no burnout)
    smoothing_kernel: width (in timesteps) of moving average filter over timeseries
    """
    #Deal with parameters (assign defaults and check correctness)
    if algs is None:
        algs = deepcopy(algorithms)

    assert not (show_quartiles and show_normal_CI)

    assert data_name in data_names
    for alg in algs:
        assert alg in algorithms
        
    assert burnin_timesteps>=0
    assert burnout_timesteps>=0
    
    #Extract what our population of interest is
    pop = get_relevant_pop_name(data_name) 

    #Load and process relevant data from files
    lower_timeseries_by_alg = {}
    middle_timeseries_by_alg = {} 
    upper_timeseries_by_alg = {} 
    for alg in algs:
        try:
            #Load file
            with open(f"project_modelling/pickled_results/{alg}.pickle", "rb") as f:
                loaded_data = pickle.load(f)
                alg_timeseriess = loaded_data[data_name] #alg_timeseries = {(seed, parametersation):[timeseries]}
                pop_timeseriess = loaded_data[pop]

            #Preprocess loaded timeserieses for easy computation of mean/std over timepoints (turn into numpy array)
            alg_timeseriess_array = []
            pop_size_array = []
            for key in alg_timeseriess.keys(): #iterate over (seed, parametersation) pairs, as this plotting does not need them as it does not do paired comparisons
                alg_timeseriess_array.append(alg_timeseriess[key])
                pop_size_array.append(pop_timeseriess[key]) #timeseries with the same (seed, parameterisation) pair have corresponding positions in alg_timeseriess_array and pop_size_array
            
            alg_timeseriess_array = np.array(alg_timeseriess_array) #shape (#timeseries, #timepoints in each timeseries)
            pop_size_array = np.array(pop_size_array)
            n,T = alg_timeseriess_array.shape
            #print(n)

            #Normalise point-wise if desired
            if normalise_per_100k:
                alg_timeseriess_array = np.divide(alg_timeseriess_array, pop_size_array) * 100_000 #multiply by 100k to get rate per 100k 

            #compute lb, m, ub to be the timeseries of lower bounds, middles, and upper bounds respectively for this alg
            if show_quartiles:
                lb, m, ub = [],[],[]
                lb = list(np.percentile(alg_timeseriess_array, 25, axis=0))
                ub = list(np.percentile(alg_timeseriess_array, 75, axis=0))
                m = list(np.percentile(alg_timeseriess_array, 50, axis=0))
            else: 
                #Compute means, stds
                means = np.mean(alg_timeseriess_array, axis=0)
                stds = np.std(alg_timeseriess_array, axis=0, ddof=1)

                #Compute confidence intervals (timepoint-wise) and add relevant timeseries to the dictionary to be plotted
                lb, ub = [], []; m = list(means)
                for t in range(T):
                    ci = stats.t.interval(
                        1-sig_level,
                        df = n-1,
                        loc = means[t],
                        scale = stds[t]/np.sqrt(n)
                    )
                    lb.append(ci[0]); ub.append(ci[1])

            lower_timeseries_by_alg[alg] = lb
            middle_timeseries_by_alg[alg] = m
            upper_timeseries_by_alg[alg] = ub            
        except Exception as e:
            print(f"Unable to open and/or process file project_modelling/pickled_results/{alg}.pickle. Omitting from plot")
            print(e)
            algs.remove(alg)

    #Smooth
    if smoothing_kernel>1:
        for alg in algs:
            lower_timeseries_by_alg[alg] = smooth_list(lower_timeseries_by_alg[alg], smoothing_kernel)
            middle_timeseries_by_alg[alg] = smooth_list(middle_timeseries_by_alg[alg], smoothing_kernel)
            upper_timeseries_by_alg[alg] = smooth_list(upper_timeseries_by_alg[alg], smoothing_kernel)

    #Plot
    for alg in algs: #algs has had any elements removed for which we could not successfully load and process data
        T = len(lower_timeseries_by_alg[alg])
        middles = middle_timeseries_by_alg[alg][burnin_timesteps:T-burnout_timesteps]
        xs = range(len(middles))

        if show_normal_CI or show_quartiles:
            lowers = lower_timeseries_by_alg[alg][burnin_timesteps:T-burnout_timesteps]
            uppers = upper_timeseries_by_alg[alg][burnin_timesteps:T-burnout_timesteps]
            ax.fill_between(xs, lowers, uppers, alpha=0.1, color=alg_colors[alg] if alg in alg_colors.keys() else None)
            ax.plot(xs, lowers, color=alg_colors[alg] if alg in alg_colors.keys() else None, linestyle='dotted', alpha=0.5)
            ax.plot(xs, uppers, color=alg_colors[alg] if alg in alg_colors.keys() else None, linestyle='dotted', alpha=0.5)
        ax.plot(xs, middles, color=alg_colors[alg] if alg in alg_colors.keys() else None, label= alg_labels[alg] if alg in alg_labels.keys() else alg) 
    return ax


