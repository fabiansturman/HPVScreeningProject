def get_timeseries_from_log(log, 
                            rescale_factor = 1/1.19,
                            start_year = 1980, dt = 0.25,
                            vacc_intro_year = 2008):
    """
    rescale_factor: we rescale all scales by this (multiplication); accounts for our modelling of the England population as 1/1.19x the UK population 
    start_year: The year which the simulation of our log starts at (i.e. the year at the time of timepoint 0)
    dt: The dt of the simulation of our log (i.e. there are 1/dt timepoints in our log for each simulated year)
    vacc_intro_year: The year in our simulation in which vaccination of teenagers begins (for defining vaccine eligibility for timeseries of eligible/ineligible conhorts)

    Takes {log}, generated from running a simulation, and extracts quantities to populate each timeseries specified in data_names.
        - NOTE: each element in data_names is either of the form '{quantity}_{population}' or '{quantity}_{population}_{genotype}', with population of interest defined in terms of vaccination state

    Returns a dictionary of results indexed by timeseries name (i.e. element in data_names)
    """
    timeseries = {result_type: [] for result_type in data_names} #we add an element to each list for each timepoint we iterate over in the log
    
    #UTILITY: Takes a np array of form (n_genotypes, pop_size) and collapses it to (pop_size) by OR-ing over the genotypes we care about for particular quantities
    genotype_collapser_from_genotype_state = {
        "_vacctypes": (lambda genotype_wise_results: np.any(genotype_wise_results[:3,:], axis=0)), #take the first three rows (these are vaccine genotypes) and then collapse over the genotype column over these remianing genotypes - any 'True's mean presence of this state in some genotype
        "_nonvacctypes": (lambda genotype_wise_results: genotype_wise_results[3,:]), #take the row of 'ohr' type, and ensure it is the boolean type
        "_alltypes": (lambda genotype_wise_results: np.any(genotype_wise_results, axis=0)), #'or' over all genotypes
    }

    #PREPARING TO LOOP OVER ALL TIMEPOINTS IN LOG: Defining trackers of simulation state between timepoints (i.e. 'memory' of what happened in the past). At the start of loop T, each tracker matches the state as it was at the end of loop T-1.
        #TEMPLATE trackers - these are not the exact ones that will be doing the tracking, as we will be making copies of them for different population and genotype partitions
    cumulative_pids_diagnosed_with_cancer = set() #keeps track of all pids diagnosed with cancer at a given timepoint; once diagnosed, even if treated, we keep them in this set in regognistion of increased followup +attention post-treatment, to reduce inflation in 'undiagnosed cancers after 5 years' for repeat cancers as likely this is a modelling artifact from our only modelling diagnosis through regular screening (while in reality if someone has had cancer, had it diagnosed and treated, and then gets it again, they are likely to have it diagnosed quickly and within 5 years; this modelling ensures such a case does not contribute to our 'UD5Y' tracker)
    previous_timestep_infectious = np.array([]) #initialised as a 1D empty array (1D with no elements); number of individuals infectious by the end of the previous timestep
    previous_timestep_cin = np.array([]) #number of individuals with CIN state at the end of the previous timestep
        
    timepoint_lag_5yr = int(5/base_pars['dt']) #number of timepoints that make up a 5-year lag (this will not be exact unless 1/dt is an int)
    pids_with_cancer_iplus1_timepoints_ago = [set() for i in range(timepoint_lag_5yr)] 
            #^ At the start of timepoint t, element i stores all agents who had cancer at the end of timepoint t-(i+1), and continually since then to the start of timepoint t.
            #Each timepoint, we are to (1) shift everything up one index by adding currently cancerous agents to the start of the list, and
            #                          (2) filter the list's sets to only incldue those currently with cancer (using INTERSECTION operations working our way down the list to ensure elemnnt i+1 is always contianed in element i)
            #                          (3) take the final element of the list, which is people who have had cancer continually for 5 years, are checked against those diagnosed to track the number of undiagosed after 5 years of continual cancer
            #NOTE: final element of list is all pids with cancer that still have it and it is at least 5 years old.
            #          To ensure this (^) holds, when we pop from the end we still put elements back into that last set again, we are essentially just combining the final two sets at each time a new set starts at the front of the list and works its way to the set of long-term cancerous agents at the back
            #We note that we do not record 'previous_timestep_pids_with_cin', as that is 'pids_with_cancer_iplus1_timepoints_ago[0]' at the start of a timestep
    
        #INSTANTIATING THE TEMPLATES: Making specific trackers for simulation state between timepoints, indexed by population and genotype of interest
    state_trackers = {}
    for population in vacc_states:
        for genotype in genotype_states:
            state_trackers[population+genotype] = [
                deepcopy(cumulative_pids_diagnosed_with_cancer),
                deepcopy(previous_timestep_infectious),
                deepcopy(previous_timestep_cin),
                deepcopy(pids_with_cancer_iplus1_timepoints_ago)
            ]

    #LOOPING OVER ALL TIMEPOINTS 
    previous_n = 0 #at timestep t=0 (first timestep), there were zero agents just before the timestep started
    for t in sorted(log.keys()):
        log_at_timepoint = log[t] #{log_at_timepoint} contains the state of the log right now.
        current_year = t*dt + start_year #find current year


        #Get which agents are vaccinated/unvaccinated
        vacc_by_pid = log_at_timepoint['vx_doses']>=1
        unvacc_by_pid = ~vacc_by_pid

        #Get which agents are eligible/ineligible for vaccination
        year_when_12_by_pid = current_year - (log_at_timepoint['age'] - 12) #for agent i, year_when_12_by_pid gives the year when this agent turns/did turn 12 years old
        eligible_by_pid = (year_when_12_by_pid >= vacc_intro_year) & (log_at_timepoint['age'] >= 12) #assumes all agents are born at the start of the year, not modelling mid-year birthdays as a possibility. Note that an individual is only eligible if they are both at least 12 years old and turned 12 late enough.
        ineligible_by_pid = ~eligible_by_pid

        #Get the scale of each agent (we assign any agent which is not female or not alive a scale of 0, so that when we aggregate agent's sacles to get number over a population, we stay within the subpopulation of interest)
        scale_by_pid = log_at_timepoint['scale'] * rescale_factor
        scale_by_pid = np.multiply(scale_by_pid, log_at_timepoint['alive'])
        scale_by_pid = np.multiply(scale_by_pid, log_at_timepoint['sex']==0) #a sex of 0 means female

        #Get current number of agents that exist in the sim
        n = log_at_timepoint['n'] #find current number of agents that exist in the sim 

        #Infectiousness tracking: "inc_infectious", "prev_infectious". Uses, then updates 'previous_timestep_pids_with_infectiousness'
        current_infectious = log_at_timepoint['infectious']

        for genotype in genotype_states:    #We loop through all considered 'scopes' of analysis in terms of genotypes of interst and in terms of vaccination-state-based population partitions
            #Restrict our focus down to the genotypes of interest
            currently_infectious_with_genotypes_of_interest = genotype_collapser_from_genotype_state[genotype](current_infectious) #boolean list, with a True or False value for each agent that exists at this timestep to say whether they are currently infectious with a genotype of interest

            for population in vacc_states:
                #Restrict our focus to the population of interest to track infectiousness for these genotypes in each subpopulation seperately
                if population == '_fullpop':
                    current_infectious_of_interest = currently_infectious_with_genotypes_of_interest
                elif population == '_vaccpop':
                    current_infectious_of_interest = np.logical_and(currently_infectious_with_genotypes_of_interest, vacc_by_pid)
                elif population == '_unvaccpop':
                    current_infectious_of_interest = np.logical_and(currently_infectious_with_genotypes_of_interest, unvacc_by_pid)
                elif population == '_eligiblepop':
                    current_infectious_of_interest = np.logical_and(currently_infectious_with_genotypes_of_interest, eligible_by_pid)
                elif population == '_ineligiblepop':
                    current_infectious_of_interest = np.logical_and(currently_infectious_with_genotypes_of_interest, ineligible_by_pid)
                elif population == '_eligibleunvaccpop':
                    current_infectious_of_interest = np.logical_and(currently_infectious_with_genotypes_of_interest, 
                                                                    np.logical_and(eligible_by_pid,unvacc_by_pid))
                else:
                    print("Unrecognised vacc state - appear to be missing a population partition in this section of get_timeseries_from_log funtion")
                    assert False
                
                #Calculate incidence - infections that are now that were not before
                previous_infectious_of_interest = state_trackers[population+genotype][1]
                num_newly_infected_existing_agents = np.dot(current_infectious_of_interest[:previous_n] > previous_infectious_of_interest, #there is a 'true' for each time an agent is newly infected, for those that existed before, and we add them up to get a count
                                                        scale_by_pid[:previous_n] #dot-multiply by each agent's scale so we add up the number of people represented by each newly infectious agent
                                                    )
                num_newly_infected_new_agents = np.dot(current_infectious_of_interest[previous_n:], scale_by_pid[previous_n:]) #all infectious agents which did not exist last timestep count towards the total incidence this timestep
                incidence = num_newly_infected_existing_agents + num_newly_infected_new_agents
                timeseries['inc_infectious'+population+genotype].append(incidence)

                #Calculate prevalence
                prevalence = np.dot(current_infectious_of_interest, scale_by_pid)
                timeseries['prev_infectious'+population+genotype].append(prevalence)
                
                #Update state tracker of infectiousness prevalence at each 'previous timepoint'
                state_trackers[population+genotype][1] = current_infectious_of_interest #don't need to do a deep copy of this array as we immediately are moving onto a different array after this loop, and are never changing the values in here anyway
    

        #CIN tracking: "inc_cin", "prev_cin". Uses, then updates 'previous_timestep_pids_with_cin'
        current_cin = log_at_timepoint['cin']

        for genotype in genotype_states:  #We loop through all considered 'scopes' of analysis in terms of genotypes of interst and subpopulations of interest
            #Restrict our focus down to the genotypes of interest
            current_cin_with_genotypes_of_interest = genotype_collapser_from_genotype_state[genotype](current_cin)

            for population in vacc_states:
                #Restrict our focus to the population of interest to track CINs for these genotypes in each subpopulation seperately
                if population == '_fullpop':
                    current_cin_of_interest = current_cin_with_genotypes_of_interest
                elif population == '_vaccpop':
                    current_cin_of_interest = np.logical_and(current_cin_with_genotypes_of_interest, vacc_by_pid)
                elif population == '_unvaccpop':
                    current_cin_of_interest = np.logical_and(current_cin_with_genotypes_of_interest, unvacc_by_pid)
                elif population == '_eligiblepop':
                    current_cin_of_interest = np.logical_and(current_cin_with_genotypes_of_interest, eligible_by_pid)
                elif population == '_ineligiblepop':
                    current_cin_of_interest = np.logical_and(current_cin_with_genotypes_of_interest, ineligible_by_pid)
                elif population == '_eligibleunvaccpop':
                    current_cin_of_interest = np.logical_and(current_cin_with_genotypes_of_interest, 
                                                                    np.logical_and(eligible_by_pid,unvacc_by_pid))
                else:
                    print("Unrecognised vacc state - appear to be missing a population partition in this section of get_timeseries_from_log funtion")
                    assert False

                #Calculate incidence - cins that are now that were not before
                previous_cin_of_interest = state_trackers[population+genotype][2]
                num_newly_cin_existing_agents = np.dot(current_cin_of_interest[:previous_n] > previous_cin_of_interest, #there is a 'true' for each time an agent is newly infected, for those that existed before, and we add them up to get a count
                                                        scale_by_pid[:previous_n] #dot-multiply by each agent's scale so we add up the number of people represented by each newly infectious agent
                                                    )
                num_newly_cin_new_agents = np.dot(current_cin_of_interest[previous_n:], scale_by_pid[previous_n:])
                incidence = num_newly_cin_existing_agents + num_newly_cin_new_agents
                timeseries['inc_cin'+population+genotype].append(incidence)

                #Calculate prevalence
                prevalence = np.dot(current_cin_of_interest, scale_by_pid)
                timeseries['prev_cin'+population+genotype].append(prevalence)
                
                #Update state tracker of cin prevalence at each 'previous timepoint'
                state_trackers[population+genotype][2] = current_cin_of_interest #don't need to do a deep copy of this array as we immediately are moving onto a different array after this loop, and are never changing the values in here anyway
    

        #Cancer tracking: "inc_cancers", "prev_cancers", "inc_cancers_diagnosed", "prev_cancers_ud5y". Uses pids_with_cancer_iplus1_timepoints_ago[0].
        current_cancerous = log_at_timepoint['cancerous']

        for genotype in genotype_states:  #We loop through all considered 'scopes' of analysis in terms of genotypes of interst and subpopulations of interest
            #Restrict our focus down to the genotype of interest
            currently_cancers_from_genotypes_of_interest = genotype_collapser_from_genotype_state[genotype](current_cancerous)

            for population in vacc_states:
                #Restrict our focus to the population of interest to track infectiousness for these genotypes in each subpopulation seperately
                if population == '_fullpop':
                    current_cancers_of_interest = currently_cancers_from_genotypes_of_interest
                elif population == '_vaccpop':
                    current_cancers_of_interest = np.logical_and(currently_cancers_from_genotypes_of_interest, vacc_by_pid)
                elif population == '_unvaccpop':
                    current_cancers_of_interest = np.logical_and(currently_cancers_from_genotypes_of_interest, unvacc_by_pid)
                elif population == '_eligiblepop':
                    current_cancers_of_interest = np.logical_and(currently_cancers_from_genotypes_of_interest, eligible_by_pid)
                elif population == '_ineligiblepop':
                    current_cancers_of_interest = np.logical_and(currently_cancers_from_genotypes_of_interest, ineligible_by_pid)
                elif population == '_eligibleunvaccpop':
                    current_cancers_of_interest = np.logical_and(currently_cancers_from_genotypes_of_interest, 
                                                                    np.logical_and(eligible_by_pid,unvacc_by_pid))
                else:
                    print("Unrecognised vacc state - appear to be missing a population partition in this section of get_timeseries_from_log funtion")
                    assert False

                #Calculate cancer incidence - cancers that are now that were not before
                pids_with_cancer_iplus1_timepoints_ago = state_trackers[population+genotype][3] #a list of nested sets
                assert len(pids_with_cancer_iplus1_timepoints_ago) == timepoint_lag_5yr #sanity check that this remains the same size always - if it changes size the logic for UD5Y has failed
            
                pids_with_cancer_at_previous_timepoint = pids_with_cancer_iplus1_timepoints_ago[0]
                pids_currently_with_cancer = set(np.where(current_cancers_of_interest)[0]) #a set of the pids of all agents currently with cancer

                pids_newly_with_cancer = list(pids_currently_with_cancer - pids_with_cancer_at_previous_timepoint) #do difference of sets, then convert to a list to do fancy indexing
                incidence = np.sum(scale_by_pid[pids_newly_with_cancer])
                timeseries['inc_cancers'+population+genotype].append(incidence)

                #Calculate cancer prevalence
                prevalence = np.sum(scale_by_pid[list(pids_currently_with_cancer)])
                timeseries['prev_cancers'+population+genotype].append(prevalence)
                
                #Update pids_with_cancer_iplus1_timepoints_ago to include current prevalence and be consistent 
                pids_with_cancer_iplus1_timepoints_ago = [pids_currently_with_cancer] + pids_with_cancer_iplus1_timepoints_ago
                for i in range(1,len(pids_with_cancer_iplus1_timepoints_ago)):
                    #To be consistent, each set in this list of sets can only incldue elements in its first set (as if an agent is not cancerous currently, it can't have been continually cancerous from any past point all the way to now, and by enforcing this every time we change the list we ensure the list is one of fully nested sets)
                    pids_with_cancer_iplus1_timepoints_ago[i] = pids_currently_with_cancer.intersection(pids_with_cancer_iplus1_timepoints_ago[i])

                #Calculate number of cancer diagnoses and update state tracker of cumulative set of cancer-diangosed pids 
                current_cancer_diagnosis_set = set(log_at_timepoint['interventions']['colposcopy']['cancer'])
                state_trackers[population+genotype][0] = state_trackers[population+genotype][0].union(current_cancer_diagnosis_set)
                num_new_diagnoses = np.sum(scale_by_pid[list(current_cancer_diagnosis_set)])
                timeseries['inc_cancers_diagnosed'+population+genotype].append(num_new_diagnoses)

                #Calcuate number undiagnosed after 5 years (cutoff: does NOT include those diagnosed exactly 5 years of timesteps after development of cancer)
                cancers_after_5_years_or_more = pids_with_cancer_iplus1_timepoints_ago.pop(-1) #get the pids of agents who have had cancer for over 5 years
                pids_with_cancer_iplus1_timepoints_ago[-1] = pids_with_cancer_iplus1_timepoints_ago[-1].union(cancers_after_5_years_or_more) #re-combine so we keep tracking all agents with cancer until they are cured
                
                pids_undiagnosed_cancers_after_5_years_or_more = cancers_after_5_years_or_more - current_cancer_diagnosis_set
                num_undiagnosed_cancers_after_5_years_or_more = np.sum(scale_by_pid[list(pids_undiagnosed_cancers_after_5_years_or_more)]) #I have defined scale_by_pid not to assign weight to agents who are no longer alive
                timeseries['prev_cancers_ud5y'+population+genotype].append(num_undiagnosed_cancers_after_5_years_or_more)

                #Update state tracker of cancers over the last 5 years of timepoints
                state_trackers[population+genotype][3] = pids_with_cancer_iplus1_timepoints_ago #don't need to do a deep copy of this array as we immediately are moving onto a different array after this loop, and are never changing the values in here anyway
        
        #Population size tracking: "popsize"
        timeseries['popsize' + '_fullpop'].append(np.sum(scale_by_pid))
        timeseries['popsize' + '_vaccpop'].append(np.dot(scale_by_pid, vacc_by_pid))
        timeseries['popsize' + '_unvaccpop'].append(np.dot(scale_by_pid, unvacc_by_pid))
        timeseries['popsize' + '_eligiblepop'].append(np.dot(scale_by_pid, eligible_by_pid))
        timeseries['popsize' + '_ineligiblepop'].append(np.dot(scale_by_pid, ineligible_by_pid))
        timeseries['popsize' + '_eligibleunvaccpop'].append(np.dot(scale_by_pid, np.logical_and(eligible_by_pid,unvacc_by_pid)))
        
        #Screening tracking: "routine_screens"
            #Get test results (note 'over 50' is inclusive, 'under 50' exclusive)
        under50_positives = log_at_timepoint['interventions']['routine_screening_under50']['positive']
        under50_inadequates = log_at_timepoint['interventions']['routine_screening_under50']['inadequate']
        under50_negatives = log_at_timepoint['interventions']['routine_screening_under50']['negative']
        over50_positives = log_at_timepoint['interventions']['routine_screening_50andover']['positive']
        over50_inadequates = log_at_timepoint['interventions']['routine_screening_50andover']['inadequate']
        over50_negatives = log_at_timepoint['interventions']['routine_screening_50andover']['negative']

        for population in vacc_states:
            #Restrict our focus down to the population of interest by furthering filtering down our scale
            if population == '_fullpop':
                filtered_scale = scale_by_pid
            elif population == '_vaccpop':
                filtered_scale = np.multiply(scale_by_pid,vacc_by_pid)
            elif population == '_unvaccpop':
                filtered_scale = np.multiply(scale_by_pid,unvacc_by_pid)
            elif population == '_eligiblepop':
                filtered_scale = np.multiply(scale_by_pid,eligible_by_pid)
            elif population == '_ineligiblepop':
                filtered_scale = np.multiply(scale_by_pid,ineligible_by_pid)
            elif population == '_eligibleunvaccpop':
                filtered_scale = np.multiply(scale_by_pid,np.logical_and(eligible_by_pid,unvacc_by_pid))
            else:
                print("Unrecognised vacc state - appear to be missing a population partition in this section of get_timeseries_from_log funtion")
                assert False

            total_screens = 0
            total_screens += np.sum(filtered_scale[under50_positives])
            total_screens += np.sum(filtered_scale[under50_inadequates])
            total_screens += np.sum(filtered_scale[under50_negatives])
            total_screens += np.sum(filtered_scale[over50_positives])
            total_screens += np.sum(filtered_scale[over50_inadequates])
            total_screens += np.sum(filtered_scale[over50_negatives])

            timeseries['routine_screens'+population].append(np.sum(total_screens))

        #Update previous n
        previous_n = n

    return timeseries

