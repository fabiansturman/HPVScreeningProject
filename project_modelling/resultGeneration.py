###- (2) RECORDING SIMULATION RESULTS AS TIMESERIES-###
"""
Each run of a HPVsim simulation generates a lot of data. 
We turn this data into a useful format as follows:
    i)      If not already made, initialise a blank 'timeseries' file which will contain all the results from a particular scenario (i.e. 'alg'). That is, for a particular simulation configuration, it stores the results from running that configuration, over multiple runs.
    ii)     Set up a HPVsim sim instance with the desired properties, and add a logging intervention (as in project_modelling/InterventionAlgorithms/simulationLogging.py) to it, with the logging intervention set to only track the particular outcomes of interventions that we care about (here, outcomes of routine screens so we can track number of routine screens and outcomes of colposcopies so we can see the number of diagnosed cancers)
    iii)    Run the sim. As it runs, properties of its state at each timepoint will be saved to a 'log' object.
    iv)     Turn the log to a set of timeseries(es): for every result type (defined in section (1) of this script), we get a dictionary {timepoint: value of this quantity at this timepoint}
    v)      Save all the timeseries(es): we save it to the pickle file for this scenario ('alg') so that the pickle file is of the format {result_type: {(seed, parameterisation_num): timeseries for that result, for the run parameterised by the 'parameterisation_num' calibrated parameter set and seed 'seed'}
"""
def initialise_blank_ts_file(algs = None):
    """
    Initialises blank timeseries (ts) files for the specified algorithms (if alg=None, does for all algorithms)
    """
    if algs is None:
        algs = algorithms
    
    for alg in algs:
        data = {}
        for data_name in data_names:
            data[data_name] = {} #to be populated as {(seed, paramaterisation_num): timeseries of the given data_name, for this algorithm, when running with this seed}
        
        
        filename = f'project_modelling/pickled_results/{alg}.pickle'

        follow_through_on_saving = False #a safety check to make sure we don't accidentally override an existing log
        if os.path.isfile(filename):
            override = input(f"File {filename} already exists. Press (y) to override, any other key to skip initialising this timeseries file.")
            if override.lower() == 'y':
                follow_through_on_saving=True
        else:
            follow_through_on_saving=True

        if follow_through_on_saving:
            with open(filename,'wb') as file:
                pickle.dump(data, file)
            print(f"Made file {filename}.")
        else:
            print("Skipping initialisation of timeseries file, due to a file with this name already existing and the file override option not being selected")

