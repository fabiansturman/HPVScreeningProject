def ttest_powerplot(ax, lower_std_bound, upper_std_bound, effect_size_lower=-4, effect_size_upper=4, alpha=sig_level, nobs=44*5):
    """
    Plots power curves onto ax for a t test (power against ground truth mean difference). Plots two curves, for upper and lower bound of ground truth variance.
    effect_size_lower and effect_size_upper give the range of ground truth effect sizes (i.e. ground truth mean differences / standard deviation of empirical mean differences) over which we plot.
    alpha is the signficance level of our statistical test and nobs is the number of independant observations involved in each t test.
    """
    from statsmodels.stats.power import TTestPower

    analysis = TTestPower()
    effect_sizes = np.linspace(effect_size_lower, effect_size_upper, 5000) # Range of effect sizes 

    power = analysis.power(effect_size=effect_sizes, nobs=nobs, alpha=alpha, alternative='two-sided')
    ax.plot(effect_sizes*lower_std_bound, power, color='blue', lw=2, label=f'σ = {lower_std_bound}')
    ax.plot(effect_sizes*upper_std_bound, power, color='red', lw=2, label=f'σ = {upper_std_bound}')

    #Find the scale we need on the x axis
    upper_x_bound = effect_sizes[np.where(power[2500:] > 1-1e-8)[0][0] + 2500]*upper_std_bound*1.2 #the 1.2 mutliplier adds a small margin
    lower_x_bound = -1 * upper_x_bound #t test's power plot is symmetric
    ax.set_xlim(lower_x_bound,upper_x_bound)
    #ax.set_xticks(np.linspace(lower_x_bound//100, upper_x_bound, 10))

    #Other plot formatting
    ax.set_title(f'Power Curve for Paired T-Test (n = {nobs}, α = {alpha})')
    ax.set_xlabel('Ground Truth Mean Difference')
    ax.set_ylabel(f'Power of Paired T Test, as performed (α = {alpha}, n={nobs})')
    plt.legend()
    ax.set_yticks(np.arange(0,1,0.1))
    ax.grid(True)

    return ax
    









