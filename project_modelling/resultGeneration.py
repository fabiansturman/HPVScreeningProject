def get_paired_difference_tss(data_name, normalise_per_100k,
                              compared_alg, baseline_alg,
                              ):
    '''
    Returns a list of timeseriess of the paired (by parameterisation and seed) differences between the provided pair of algorithms for the specified quantity.
    data_name (str): the name of timeseries we will be returning paired differences of
    normalise_per_100k (bool): whether to deal with the timeseries in terms of raw numbers, or as rates
    compared_alg (str): the name of the algorithm from whose results we will be subtracting values to get the differences (X in X-Y)
    baseline_alg (str): the name of the algorithm whose results we use to subtract with (Y in X-Y)
    
    Returns:    dict( (seed, param):[timeseries of differences] for each param-seed pair that is successfully paired between the two algs ), 
                set(unpaired param-seed pairs for compared), 
                set(unpaired param-seed pairs for baseline)
    '''
    #Check correctness of parameters
    assert data_name in data_names
    assert compared_alg in algorithms
    assert baseline_alg in algorithms

    #Extract what our population of interest is (we will only use the pop variable if {normalise_per_100k})
    pop = get_relevant_pop_name(data_name) 

    #Load data from each alg (from both algs, load population over time and the quantity of interest, {data_name}, over time)
    compared_timeseries, baseline_timeseries = None, None #timeseries are of the form {(seed, parameterisation index): [list of values as they vary over timepoints]}
    compared_pops, baseline_pops = None, None
    try:
        with open(f"project_modelling/pickled_results/{compared_alg}.pickle", "rb") as f:
            loaded_data = pickle.load(f)
            compared_timeseries = loaded_data[data_name]
            if normalise_per_100k:
                compared_pops = loaded_data[pop]

        with open(f"project_modelling/pickled_results/{baseline_alg}.pickle", "rb") as f:
            loaded_data = pickle.load(f)
            baseline_timeseries = loaded_data[data_name] 
            if normalise_per_100k:
                baseline_pops = loaded_data[pop]

        assert compared_timeseries is not None
        assert baseline_timeseries is not None
        if normalise_per_100k:
            assert compared_pops is not None
            assert baseline_pops is not None
    except:
        print("Unable to open one of the required timeseries")

    #Convert each timeseries to numpy array for ease of operations, and normalise per 100k if relevant
    if normalise_per_100k:
        for seed, param_index in compared_timeseries.keys():
            raw_values = np.array(compared_timeseries[(seed, param_index)])
            pop_sizes = np.array(compared_pops[(seed, param_index)])
            normalised_values = raw_values/pop_sizes * 100_000
            compared_timeseries[(seed, param_index)] = normalised_values

        for seed, param_index in baseline_timeseries.keys():
            raw_values = np.array(baseline_timeseries[(seed, param_index)])
            pop_sizes = np.array(baseline_pops[(seed, param_index)])
            normalised_values = raw_values/pop_sizes * 100_000
            baseline_timeseries[(seed, param_index)] = normalised_values
    else:
        for seed, param_index in compared_timeseries.keys():
            compared_timeseries[(seed, param_index)] = np.array(compared_timeseries[(seed, param_index)])

        for seed, param_index in baseline_timeseries.keys():
            baseline_timeseries[(seed, param_index)] = np.array(baseline_timeseries[(seed, param_index)])

    #Compute timeserieses of differences
    difference_timeserieses = dict()
    unmatched_compared = set()
    for seed, param_index in compared_timeseries.keys():
        if (seed, param_index) in baseline_timeseries.keys():
            difference_timeserieses[(seed, param_index)] = compared_timeseries[(seed, param_index)] - baseline_timeseries[(seed, param_index)]
        else:
            unmatched_compared.add((seed, param_index))         
    unmatched_baseline = set(baseline_timeseries.keys()) - set(difference_timeserieses.keys())
    
    return difference_timeserieses, unmatched_compared, unmatched_baseline

def get_simple_totals(data_name, start_tp = 0, end_tp=0, 
                        normalise_per_100k=False, algs=[] ,
                        accepted_paramandseeds = None):
    """
    For each algorithm in algs, returns a list of all the sums between start_tp and end_tp (inclusive) for data_name. Formatted as a dictionary.

    data_name (str): the name of timeseries we will be returning sums of
    start_tp: inclusive bound for the start of the sum
    end_tp: inclusive bound for the end of the sum
    normalise_per_100k (bool): whether to deal with the timeseries in terms of raw numbers, or as rates
    algs: the screening algorithms to calculate for
    accepted_paramandseeds: If specified, defines the set of parameter-seed pairs which we use (all others are not used). Otherwise, plots all.

    
    Returns:  {alg: [totals of data_name between timepoints [start_tp, end_tp] for alg in algs]}
    """
    #Check correctness of parameters
    assert data_name in data_names
    assert start_tp>=0 and start_tp<=end_tp
    for alg in algs:
        assert alg in algorithms

    #Extract what our population of interest is (we will only use the pop variable if {normalise_per_100k})
    pop = get_relevant_pop_name(data_name) 

    #Compute the totals, algorithm-by-algorithm
    totals_by_alg = {alg:[] for alg in algs}
    for alg in tqdm(algs):
        try:
            #Load data: load both population over time and quantity of interest ({data_name}) over time 
            data_timeseries = None #these are of the form {(seed, parameterisation index): [list of values consittuing the timeseries from the simulation with that seed and parameterisation]}
            pop_timeseries = None

            with open(f"project_modelling/pickled_results/{alg}.pickle", 'rb') as f:
                loaded_data = pickle.load(f)
                data_timeseries = loaded_data[data_name]
                if normalise_per_100k:
                    pop_timeseries = loaded_data[pop]
            
            #Check the loaded data is correct (i.e. the data we were looking for was in the file we wanted it to be in)
            assert data_timeseries is not None
            if normalise_per_100k:
                assert pop_timeseries is not None

            #Filter for the simulation runs we have accepted for analysis
            if accepted_paramandseeds is None:
                accepted_paramandseeds = set(data_timeseries.keys())
            else:
                accepted_paramandseeds = accepted_paramandseeds.intersection(set(data_timeseries.keys()))
            
            #Compute totals
            for seed, param_index in accepted_paramandseeds:
                #Convert this loaded timeseries to numpy array for ease of operations, normalising if needed
                vs = np.array(data_timeseries[(seed, param_index)])
                if normalise_per_100k:
                    pop_sizes = np.array(pop_timeseries[(seed, param_index)])
                    vs = vs/pop_sizes * 100_000
                
                #Compute total for this loaded timeseries
                total = sum(vs[start_tp: end_tp+1])
                totals_by_alg[alg].append(total)

        except:
            print(f"Error processing  alg {alg}")

    return totals_by_alg

def get_total_diffs(data_name, compared_alg, baseline_alg,
                    start_tp=0, end_tp=0,
                    normalise_per_100k=False,
                    accepted_paramandseeds = None):
    """
    For each algorithm in algs, returns all the differences between compared_alg and baseline_alg in the quantity {data_name} between timepoints start_tp and end_tp inclusive.

    data_name (str): the name of quantitiy/timeseries we are interested in
    compared_alg (str): the name of the algorithm from whose results we will be subtracting values to get the differences (X in X-Y)
    baseline_alg (str): the name of the algorithm whose results we use to subtract with (Y in X-Y)
    start_tp: inclusive bound for the start of the sum
    end_tp: inclusive bound for the end of the sum
    normalise_per_100k (bool): whether to deal with the timeseries in terms of raw numbers, or as rates
    accepted_paramandseeds: If specified, defines the set of parameter-seed pairs which we use (all others are not used). Otherwise, plots all.

    Returns:  Returns:    [list of difference-sums], including each param-seed pair that is successfully paired between the two algs, 
                set(unpaired param-seed pairs for compared), 
                set(unpaired param-seed pairs for baseline)
    
    """
    #Check correctness of parameters
    assert data_name in data_names
    assert compared_alg in algorithms
    assert baseline_alg in algorithms
    assert start_tp>=0 and start_tp<=end_tp

    #Find all the timeseriess of differences in dataname between the two algorithms
    difference_timeseriess, unpairedcompared, unpairedbaseline = get_paired_difference_tss(data_name, normalise_per_100k, compared_alg, baseline_alg)

    #Filter for the simulation runs we have accepted for analysis
    if accepted_paramandseeds is None:
        accepted_paramandseeds = set(difference_timeseriess.keys())
    else:
        accepted_paramandseeds = accepted_paramandseeds.intersection(set(difference_timeseriess.keys()))

    #Find the sums for each difference timeseries
    difference_sums = []
    for seed, param_index in accepted_paramandseeds:
        dts = difference_timeseriess[(seed, param_index)]
        difference_sums.append(sum(dts[start_tp: end_tp+1]))

    return difference_sums,unpairedcompared, unpairedbaseline

