def get_timseries_from_log(log, rescale_factor = 1/1.19):
    """
    rescale_factor: we rescale all scales by this (multiplication); accounts for our modelling of the England population as 1/1.19x the UK population 

    Takes {log}, generated from running a simulation, and extracts quantities to populate each timeseries specified in data_names.
    Returns a dictionary of results indexed by timeseries name (i.e. element in data_names)
    """
    timeseries = {result_type: [] for result_type in data_names} #we add an element to each list for each timepoint we iterate over in the log

    #Takes a np array of form (n_genotypes, pop_size) and collapses it to (pop_size) by OR-ing over the genotypes we care about for particular quantities
    genotype_collapser_from_genotype_state = {
        "_vacctype": (lambda genotype_wise_results: np.any(genotype_wise_results[:3,:], axis=0)), #take the first three rows (these are vaccine genotypes) and then collapse over the genotype column over these remianing genotypes - any 'True's mean presence of this state in some genotype
        "_unvacctype": (lambda genotype_wise_results: np.array(genotype_wise_results[3,:], dtype=bool)), #take the row of 'ohr' type, and ensure it is the boolean type
        "_alltypes": (lambda genotype_wise_results: np.any(genotype_wise_results, axis=0)), #'or' over all genotypes
    }


    #Templates of trackers of simulation state between timepoints
        #cumulative trackers (at the start of each loop, keeps track of a cumualtive state up to the end of the previous loop)
    cumulative_pids_diagnosed_with_cancer = set() #keeps track of all pids diagnosed with cancer at a given timepoint; once diagnosed, even if treated, we keep them in this set in regognistion of increased followup +attention post-treatment, to reduce inflation in 'undiagnosed cancers after 5 years' for repeat cancers as likely this is a modelling artifact from our only modelling diagnosis through regular screening 
        
        #previous-timestep trackers (at the start of each loop, keeps track of state at the end of the previous loop)- for calculating incidence
    previous_timestep_infectious = np.array([]) #a 1D empty array (1D with no elements)
    previous_timestep_cin = np.array([]) 
        
        #5-year-ago trackers (at the start of loop t, has the state as of the end of loop t-5/dt)
    timepoint_lag_5yr = int(5/base_pars['dt']) #number of timepoints that make up a 5-year lag (this will not be exact unless 1/dt is an int)
    pids_with_cancer_iplus1_timepoints_ago = [set() for i in range(timepoint_lag_5yr)] 
            #^ At the start of timepoint t, element i stores all agents who had cancer at the end of timepoint t-(i+1), and continually since then to the start of timepoint t.
            #Each timepoint, we are to (1) shift everything up one index by adding currently cancerous agents to the start of the list, and
            #                          (2) filter the list's sets to only incldue those with continual cancer, using INTERSECTION operations to ensure elemnnt i+1 is always contianed in element i
            #                          (3) take the final element of the list, which is people who have had cancer continually for 5 years, are checked against those diagnosed to track the number of undiagosed after 5 years of continual cancer
            #NOTE: final element of loist is all pids with cancer that still have it and it is at least 5 years old; when we pop from the end we still put elements back into that last set again, we are essentially just combining the final two sets at each time a new set starts at the front of the list and works its way to the set of long-term cancerous agents at the back
            #We note that we do not record 'previous_timestep_pids_with_cin', as that is 'pids_with_cancer_iplus1_timepoints_ago[0]' at the start of a timestep
    
    #Specific trackers for simulation state between timepoints, indexed by population and genotype of interest
    state_trackers = {}
    for vacc_state in vacc_states:
        for genotype_state in genotype_states:
            state_trackers[vacc_state+genotype_state] = [
                deepcopy(cumulative_pids_diagnosed_with_cancer),
                deepcopy(previous_timestep_infectious),
                deepcopy(previous_timestep_cin),
                deepcopy(pids_with_cancer_iplus1_timepoints_ago)
            ]
    previous_n = 0 

    for t in sorted(log.keys()):
        log_at_timepoint = log[t]

        #Get which agents are vaccinated/unvaccinated
        vacc_by_pid = log_at_timepoint['vx_doses']>=1
        unvacc_by_pid = ~vacc_by_pid

        #Get the scale of each agent (we assign any agent which is not female or not alive a scale of 0, so that when we aggregate agent's sacles to get number over a population, we stay within the subpopulation of interest)
        scale_by_pid = log_at_timepoint['scale'] * rescale_factor
        scale_by_pid = np.multiply(scale_by_pid, log_at_timepoint['alive'])
        scale_by_pid = np.multiply(scale_by_pid, log_at_timepoint['sex']==0) #a sex of 0 means female


        n = log_at_timepoint['n']

        
        #Infectiousness tracking: "inc_infectious", "prev_infectious". Uses, then updates 'previous_timestep_pids_with_infectiousness'
        current_infectious = log_at_timepoint['infectious']

        for genotype_state in genotype_states:    #We loop through all considered 'scopes' of analysis in terms of genotypes of interst and subpopulations of interest
            #Restrict our focus down to the genotype of interest
            current_infectious_genotypescollapsed = genotype_collapser_from_genotype_state[genotype_state](current_infectious)
            for vacc_state in vacc_states:
                #Restrict our focus down to the population of interest (make all others 'false')
                if vacc_state == '_vaccpop':
                    current_infectious_of_interest = np.logical_and(current_infectious_genotypescollapsed, vacc_by_pid)
                elif vacc_state == '_unvaccpop':
                    current_infectious_of_interest = np.logical_and(current_infectious_genotypescollapsed, unvacc_by_pid)
                elif vacc_state == '_allpop':
                    current_infectious_of_interest = current_infectious_genotypescollapsed
                else:
                    print("Unrecognised vacc state")
                    assert False
                
                #Calculate incidence - infections that are now that were not before
                previous_infectious_of_interest = state_trackers[vacc_state+genotype_state][1]
                newly_infected_existing_agents = np.dot(current_infectious_of_interest[:previous_n] > previous_infectious_of_interest, #there is a 'true' for each time an agent is newly infected, for those that existed before, and we add them up to get a count
                                                        scale_by_pid[:previous_n] #dot-multiply by each agent's scale so we add up the number of people represented by each newly infectious agent
                                                    )
                newly_infected_new_agents = np.dot(current_infectious_of_interest[previous_n:], scale_by_pid[previous_n:])
                incidence = newly_infected_existing_agents + newly_infected_new_agents
                timeseries['inc_infectious'+vacc_state+genotype_state].append(incidence)

                #Calculate prevalence
                prevalence = np.dot(current_infectious_of_interest, scale_by_pid)
                timeseries['prev_infectious'+vacc_state+genotype_state].append(prevalence)
                
                #Update state tracker of infectiousness prevalence at each 'previous timepoint'
                state_trackers[vacc_state+genotype_state][1] = current_infectious_of_interest #don't need to do a deep copy of this array as we immediately are moving onto a different array after this loop, and are never changing the values in here anyway
    

        #CIN tracking: "inc_cin", "prev_cin". Uses, then updates 'previous_timestep_pids_with_cin'
        current_cin = log_at_timepoint['cin']

        for genotype_state in genotype_states:  #We loop through all considered 'scopes' of analysis in terms of genotypes of interst and subpopulations of interest
            #Restrict our focus down to the genotype of interest
            current_cin_genotypescollapsed = genotype_collapser_from_genotype_state[genotype_state](current_cin)
            for vacc_state in vacc_states:
                #Restrict our focus down to the population of interest (make all others 'false')
                if vacc_state == '_vaccpop':
                    current_cin_of_interest = np.logical_and(current_cin_genotypescollapsed, vacc_by_pid)
                elif vacc_state == '_unvaccpop':
                    current_cin_of_interest = np.logical_and(current_cin_genotypescollapsed, unvacc_by_pid)
                elif vacc_state == '_allpop':
                    current_cin_of_interest = current_cin_genotypescollapsed
                else:
                    print("Unrecognised vacc state")
                    assert False
                
                #Calculate incidence - cins that are now that were not before
                previous_cin_of_interest = state_trackers[vacc_state+genotype_state][2]
                newly_cin_existing_agents = np.dot(current_cin_of_interest[:previous_n] > previous_cin_of_interest, #there is a 'true' for each time an agent is newly infected, for those that existed before, and we add them up to get a count
                                                        scale_by_pid[:previous_n] #dot-multiply by each agent's scale so we add up the number of people represented by each newly infectious agent
                                                    )
                newly_cin_new_agents = np.dot(current_cin_of_interest[previous_n:], scale_by_pid[previous_n:])
                incidence = newly_cin_existing_agents + newly_cin_new_agents
                timeseries['inc_cin'+vacc_state+genotype_state].append(incidence)

                #Calculate prevalence
                prevalence = np.dot(current_cin_of_interest, scale_by_pid)
                timeseries['prev_cin'+vacc_state+genotype_state].append(prevalence)
                
                #Update state tracker of cin prevalence at each 'previous timepoint'
                state_trackers[vacc_state+genotype_state][2] = current_cin_of_interest #don't need to do a deep copy of this array as we immediately are moving onto a different array after this loop, and are never changing the values in here anyway
    

        #Cancer tracking: "inc_cancers", "prev_cancers". Uses pids_with_cancer_iplus1_timepoints_ago[0].
        current_cancerous = log_at_timepoint['cancerous']

        for genotype_state in genotype_states:  #We loop through all considered 'scopes' of analysis in terms of genotypes of interst and subpopulations of interest
            #Restrict our focus down to the genotype of interest
            current_cancers_genotypescollapsed = genotype_collapser_from_genotype_state[genotype_state](current_cancerous)
            for vacc_state in vacc_states:
                #Restrict our focus down to the population of interest (make all others 'false')
                if vacc_state == '_vaccpop':
                    current_cancers_of_interest = np.logical_and(current_cancers_genotypescollapsed, vacc_by_pid)
                elif vacc_state == '_unvaccpop':
                    current_cancers_of_interest = np.logical_and(current_cancers_genotypescollapsed, unvacc_by_pid)
                elif vacc_state == '_allpop':
                    current_cancers_of_interest = current_cancers_genotypescollapsed
                else:
                    print("Unrecognised vacc state")
                    assert False
                
                #Calculate cancer incidence - cins that are now that were not before
                pids_with_cancer_iplus1_timepoints_ago = state_trackers[vacc_state+genotype_state][3] #a list of nested sets
            
                pids_with_cancer_at_previous_timepoint = pids_with_cancer_iplus1_timepoints_ago[0]
                pids_currently_with_cancer = set(np.where(current_cancers_of_interest)[0]) #a set of the pids of all agents currently suffering with cancer

                pids_newly_with_cancer = pids_currently_with_cancer - pids_with_cancer_at_previous_timepoint
                pids_newly_with_cancer = list(pids_newly_with_cancer) #convert to a list to do fancy indexing
                incidence = np.sum(scale_by_pid[pids_newly_with_cancer])
                timeseries['inc_cancers'+vacc_state+genotype_state].append(incidence)

                #Calculate cancer prevalence
                prevalence = np.sum(scale_by_pid[list(pids_currently_with_cancer)])
                timeseries['prev_cancers'+vacc_state+genotype_state].append(prevalence)
                
                #Update pids_with_cancer_iplus1_timepoints_ago to include current prevalence and be consistent 
                pids_with_cancer_iplus1_timepoints_ago = [pids_currently_with_cancer] + pids_with_cancer_iplus1_timepoints_ago
                for i in range(1,len(pids_with_cancer_iplus1_timepoints_ago)):
                    #To be consistent, each set in this list of sets can only incldue elements in its first set (as if an agent is not cancerous currently, it can't have been continually cancerous from any past point all the way to now, and by enforcing this every time we change the list we ensure the list is one of fully nested sets)
                    pids_with_cancer_iplus1_timepoints_ago[i] = pids_currently_with_cancer.intersection(pids_with_cancer_iplus1_timepoints_ago[i])

                #Calculate number of cancer diagnoses and update state tracker of cumulative set of cancer-diangosed pids 
                current_cancer_diagnosis_set = set(log_at_timepoint['interventions']['colposcopy']['cancer'])
                state_trackers[vacc_state+genotype_state][0] = state_trackers[vacc_state+genotype_state][0].union(current_cancer_diagnosis_set)
                new_diagnoses = np.sum(scale_by_pid[list(current_cancer_diagnosis_set)])
                timeseries['inc_cancers_diagnosed'+vacc_state+genotype_state].append(new_diagnoses)

                #Calcuate number undiagnosed after 5 years (cutoff: does NOT include those diagnosed exactly 5 years of timesteps after development of cancer)
                cancers_after_5_years_or_more = pids_with_cancer_iplus1_timepoints_ago.pop(-1) #get the pids of agents who have had cancer for over 5 years
                pids_with_cancer_iplus1_timepoints_ago[-1] = pids_with_cancer_iplus1_timepoints_ago[-1].union(cancers_after_5_years_or_more) #re-combine so we keep tracking all agents with cancer until they are cured
                
                undiagnosed_cancers_after_5_years_or_more = cancers_after_5_years_or_more - current_cancer_diagnosis_set
                undiagnosed_cancers_after_5_years_or_more = np.sum(scale_by_pid[list(undiagnosed_cancers_after_5_years_or_more)]) #I have defined scale_by_pid not to assign weight to agents who are no longer alive
                timeseries['prev_cancers_undiagnosed_after_5_years'+vacc_state+genotype_state].append(undiagnosed_cancers_after_5_years_or_more)

                #Update state tracker of cancers over the last 5 years of timepoints
                state_trackers[vacc_state+genotype_state][3] = pids_with_cancer_iplus1_timepoints_ago #don't need to do a deep copy of this array as we immediately are moving onto a different array after this loop, and are never changing the values in here anyway
    

        #Population size tracking: "popsize"
        timeseries['popsize'+"_vaccpop"].append(np.dot(scale_by_pid, vacc_by_pid))
        timeseries['popsize'+"_unvaccpop"].append(np.dot(scale_by_pid, unvacc_by_pid))
        timeseries['popsize'+"_allpop"].append(np.sum(scale_by_pid))

        #Screening tracking: "routine_screens"
            #Get test results (note 'over 50' is inclusive, 'under 50' exclusive)
        under50_positives = log_at_timepoint['interventions']['routine_screening_under50']['positive']
        under50_inadequates = log_at_timepoint['interventions']['routine_screening_under50']['inadequate']
        under50_negatives = log_at_timepoint['interventions']['routine_screening_under50']['negative']
        over50_positives = log_at_timepoint['interventions']['routine_screening_50andover']['positive']
        over50_inadequates = log_at_timepoint['interventions']['routine_screening_50andover']['inadequate']
        over50_negatives = log_at_timepoint['interventions']['routine_screening_50andover']['negative']

        for vacc_state in vacc_states:
            #Restrict our focus down to the population of interest by furthering filtering down our scale
            if vacc_state == '_vaccpop':
                filtered_scale = np.multiply(scale_by_pid,vacc_by_pid)
            elif vacc_state == '_unvaccpop':
                filtered_scale = np.multiply(scale_by_pid,unvacc_by_pid)
            elif vacc_state == '_allpop':
                filtered_scale = scale_by_pid
            else:
                print("Unrecognised vacc state")
                assert False

            total_screens = 0
            total_screens += np.sum(filtered_scale[under50_positives])
            total_screens += np.sum(filtered_scale[under50_inadequates])
            total_screens += np.sum(filtered_scale[under50_negatives])
            total_screens += np.sum(filtered_scale[over50_positives])
            total_screens += np.sum(filtered_scale[over50_inadequates])
            total_screens += np.sum(filtered_scale[over50_negatives])

            timeseries['routine_screens'+vacc_state].append(np.sum(total_screens))


        #Update previous n
        previous_n = n

    return timeseries


def smooth_list(xs, smoothing_width):
    xs_smoothed = []
    for i in range(len(xs)):
        av = 0
        for j in range(smoothing_width):
            if i+j<len(xs):
                av += xs[i+j]
        av/=smoothing_width
        xs_smoothed.append(av)
    return xs_smoothed

def plot_quant_over_time(ax, 
                         data_name, normalise_per_100k = True,
                         algs=None, show_quartiles = False, show_normal_CI = False,
                         alg_colors={}, alg_labels={},
                         burnin_timesteps=4*20, burnout_timesteps = 4*5, smoothing_kernel=4):
    """
    ax: matplotlib.pyplot Axis object on which to plot
    data_name: what is to be plotted on the y axis (data_name<-data_names)
    normalise_per_100k: whether to plot all data per 100k members of the population from which data_name is taken (all agents, all vaccinated agents, or all unvaccinated agents)

    algs: the algorithms to be plotted (algs is to be a subset of screening_algorithms)
    show_quartiles: if True, plots median curve at each timepoint bounded by LQ and UQ. 
    show_normal_CI: If True, plots mean and the t-test confidence interval around the mean.
        NOTE: show_quartiles and show_normal_CI cannot simultaneously be true

    alg_colors (dict): dictionary mapping elements of algs to colors for their matplotlib plotting. If None, sticks with default matplotlib colors
    alg_labels (dict): dictionary mapping elements of algs to names for them for thier matplotlib plotting. If left as default, sticks with internal names as in algs

    burnin_timesteps: the number of timesteps to ignore at the start of the plot, for burnin
    burnout_timesteps: the number of timesteps to ignore at the end of the plot, s.t. post-moving-average-smoothing we don't get an incorrect dropoff at the end of the plot (if 0, no burnout)
    smoothing_kernel: width (in timesteps) of moving average filter over timeseries
    """
    #Deal with parameters (assign defaults and check correctness)
    if algs is None:
        algs = deepcopy(screening_algorithms)

    assert not (show_quartiles and show_normal_CI)

    assert data_name in data_names
    for alg in algs:
        assert alg in screening_algorithms
        
    assert burnin_timesteps>=0
    assert burnout_timesteps>=0
    
    #Extract what our population of interest is
    pop = None
