"""
    Each simulation's log cotains a lot of data - we condense this into dictionaries of timeseries.
    We generate a 'timeseries' (a list - not a dictionary) for each quantity of interest from each simulation, and index the timeseries by properties of the simulation that allow for pairing (for paired t tests).
    Timeseries are stored in .pickle files, where there is one .pickle file for each algorithm
"""
def initialise_blank_ts_file(algs = None):
    """
    Initialises blank timeseries (ts) files for the specified algorithms (if alg=None, does for all algorithms)
    """
    if algs is None:
        algs = screening_algorithms
    
    for alg in algs:
        data = {}
        for data_name in data_names:
            data[data_name] = {} #to be populated as {(seed, paramaterisation_num): timeseries of the given data_name, for this algorithm, when running with this seed}
        
        
        filename = f'{alg}.pickle'

        follow_through_on_saving = False #a safety check to make sure we don't accidentally override an existing log
        if os.path.isfile(filename):
            override = input(f"File {filename} already exists. Press (y) to override, any other key to skip initialising this timeseries file.")
            if override.lower() == 'y':
                follow_through_on_saving=True
        else:
            follow_through_on_saving=True

        if follow_through_on_saving:
            with open(filename,'wb') as file:
                pickle.dump(data, file)
            print(f"Made file {filename}.")
        else:
            print("Skipping initialisation of timeseries file, due to a file with this name already existing and the file override option not being selected")


def save_timeseries_from_log(log, seed, parameterisation_num, alg):
    """
    Gets results from {log}, generated by running a simulation with screening algorithm alg<-screening_algorithms and seed {seed}, and adds the results from this run to the result file, with each result indexed by seed.
    """
    filename = f"{alg}.pickle"
    #Load in file we will be adding the timeseries to
    try:
        with open(filename,'rb') as file:
            data = pickle.load(file) 
            print("Successfully loaded data file, and will be adding processed timeseries to this file.")
    except:
        print("No data file found to add data to. Exiting programme to avoid damage to any saved data.")
        quit(0)

    #Generate the timeseries
    timeserieses = get_timseries_from_log(log)

    #For each timeseries in timeseriess, add it (with the seed and the parameter set used for HPVsim as an index) to the log
    for data_name in data_names:
        data[data_name][(seed, parameterisation_num)] = timeserieses[data_name]

    #Save
    with open(filename,'wb') as file:
        pickle.dump(data, file)
    

