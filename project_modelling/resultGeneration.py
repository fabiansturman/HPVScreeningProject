"""
This file defines the core trunk of functionality to extract modelling results from HPVsim runs.

It defines:
    (1) 'Global variables' to be used thorughout our modelling which relate to results (significance level ofr confidence intervals, the names we are using for the different algorithms being tested, the sorts of results we are extracting, etc)
    (2) Functionality to run a HPVsim simulation, log the state of the simulation as-we-go (making use of project_modelling/InterventionAlgorithms/simulationLogging.py), and then turn that logged state into a set of timeseries(es) of interest which are then saved to a pickle file (this culminates in the 'run_sim_and_save_raw_result' function, which is used by project_modelling/run_model.py)
    (3) Functionality to run a HPVsim simulation and calculate and record a histogram of HPV infections by age at specified years (infection histogram snapshots)
    (4) Some utility functionality - helper functions for then generating final, presentable, results
    (5) Functionality to generate final, presentable, results from these timeseries files. 
    (6) Functionality to generate 'helper' results. These are results which are final and presentable but not generated from the timeseries files (e.g. power plots for paired t tests) 
    
The .pickle files generated by the functionality in (2) offer quantities as follows:
    The file stores a dictionary {name of quantity: {(seed, parameterisation_num): timeseries of this quantity}},
            where 
                (seed, parameterisation_num) identifies the set of calibrated parmeters, and random seed, used to set up our HPVsim simulation for generating the timeseries of that particular quantity
                the quantity name is of the form 'measurement_population' or 'measurement_population_genotype', as below (***)
    ***
    We record several quantitites over time for our simulation, and each quantity may be recorded over a number of subpopulations as well as the population as a whole, as appropriate for the analysis we want to complete.
    We therefore first define a number of partitions over our population - these are also referred to as 'vacc_state' in the code as they refer to the state of an agent in terms of vaccination:
        - 'fullpop': the full population of interest (in the model, all women)
        - 'vaccpop': the full vaccinated population of interest (in the model, all vaccinated women)
        - 'unvaccpop': the full unvaccinated population of interest (in the model, all unvaccinated women)
        - 'eligiblepop': the full vaccination-eligible population of interest (in the model, all women offered a vaccine as a teen)
        - 'ineligiblepop': the full vaccination-ineligible population of interest (in the model, all women not offered a vaccine as a teen)
        - 'eligibleunvaccpop': the full unvaccinated, vaccine-eligible population of interest (in the model, all women offered a vaccine as a teen that remain unvaccinated)
    We also record quantities over different genotypes:
        - 'alltypes': all genotypes
        - 'vacctypes': only genotypes included in the nonavalent vaccine (e.g. if we are looking at a cancer incidence timeseries restricted to vacctypes, then we are only looking at cancers attributable to genotypes included in the nonavalent vaccine)
        - 'nonvacctypes': only genotypes not included in the nonavalent vaccine
    We then record the following quantities for all combinations of population partition and genotypes:
        -'inc_infectious': incidence of new infectious individuals
        -'inc_cin': incidence of new individuals with CIN state
        -'inc_cancers': incidence of new individuals with cancer
        -'inc_cancers_diagnosed': incidence of new cancer diagnoses (through colposcopy triggered by regular screening only)
        -'inc_cancer_deaths': incidence of deaths due to cancer
        -'prev_infectious': prevalence of infectious individuals 
        -'prev_cin': prevalence of individuals with CIN state
        -'prev_cancers': prevalence of individuals with cancer 
        -'prev_cancers_ud5y': prevalence of individuals who currently have a cancer that is undiagnosed and has been continually present for at least the last 5 years
    Finally, the following quantities are not related to genotypes, so only recorded for each population partition:
        -'routine_screens': the number of adminsitered routine screening interventions
        -'popsize': the number of (living) individuals in this population at this timepoint
    ***

The functions available in (5) are listed below:
-> plot_quant_over_time: plotting a quantity over time, with 95% CIs or quartiles shown, for the desired selection of algorithms
-> plot_x_per_y: plot ratio between two quantities for a specified set of algorithms
-> plot_paired_difference_tss: plot the timeseries of differences corresponding to a particular row/column in a get_alg_comparison_grid plot 
-> plot_sum_barchart: plots a barchart of total of a quantity, with quartiles shown in superimposed error bars, between two timepoints for the desired selection of algorithms
-> plot_sum_barchart_all_vacc_levels: as above, but plots the barchart for the provided algorithms alongisde that algorithm with "_LV" and "_HV" appended
-> plot_alg_comparison_grid: plots a grid doing a pairwise comparison between all specified algorithms, in terms of a specified quantity and between two specified timepoints
-> get_elimination_table: Generates a CSV file of an 'elimination table' for a specified set of algs, data quantity, and timepoints between which to sum, where we report the empirical probability of the sum being under a specified threshold.

The functions available in (6) are listed below:
-> ttest_powerplot: plots power curves for a t test, to understand the power of the t-tests represented in the results of (5)
"""

