def plot_x_per_y(ax, 
                 data_name_x, data_name_y, 
                 normalise_per_100k = False,
                 algs=None, show_quartiles = False, show_normal_CI = False,
                 alg_colors=algorithm_colors, alg_labels=algorithm_labels,
                 burnin_timesteps=4*20, burnout_timesteps = 4*5, smoothing_kernel=4,
                 accepted_paramandseeds = None,
                 reciprocate = False):
    """
    Plots the ratio x/y over time (e.g. for plotting number of screens per positive cancer diagnosis). Finds ratio by pairing timeseries on parameterisation and seed.

    ax: matplotlib.pyplot Axis object on which to plot
    data_name_x: numerator of ratio to be plotted on the y axis (data_name_x<-data_names)
    data_name_y: denominator of ratio to be plotted on the y axis (data_name_y<-data_names)
        NOTE: if y is 0, division by this is undefined and behaviour of the function becomes nuanced (in some cases it will miss out plotting for undefeined timepoints, in other cases it will not plot anything meaningful at all). This is not being changed as it is a pretty desired behaviour, and is accompaied by division by zero warnings in the console to alert the user.
    normalise_per_100k: if True, we do the ratio of rates, else we do the raw ratio (the 'per 100k' is really redundant, and only included for naming consistnecy with other functions)

    algs: the algorithms to be plotted (algs is to be a subset of algorithms)
    show_quartiles: if True, plots median curve at each timepoint bounded by LQ and UQ. 
    show_normal_CI: If True, plots mean and the t-test confidence interval around the mean.
        NOTE: show_quartiles and show_normal_CI cannot simultaneously be true

    alg_colors (dict): dictionary mapping elements of algs to colors for their matplotlib plotting. If None, sticks with default matplotlib colors
    alg_labels (dict): dictionary mapping elements of algs to names for them for thier matplotlib plotting. If left as default, sticks with internal names as in algs

    burnin_timesteps: the number of timesteps to ignore at the start of the plot, for burnin
    burnout_timesteps: the number of timesteps to ignore at the end of the plot, s.t. post-moving-average-smoothing we don't get an incorrect dropoff at the end of the plot (if 0, no burnout)
    smoothing_kernel: width (in timesteps) of moving average filter over timeseries
    
    accepted_paramandseeds: If specified, defines the set of parameter-seed pairs which we use (all others are not used). Otherwise, plots all.
    
    reciprocate: Do everything x/y in calculations  and then actually plot y/x
    """
    #Deal with parameters (assign defaults and check correctness)
    if algs is None:
        algs = deepcopy(algorithms)

    assert not (show_quartiles and show_normal_CI)
    assert data_name_x in data_names
    assert data_name_y in data_names

    for alg in algs:
        assert alg in algorithms
        
    assert burnin_timesteps>=0
    assert burnout_timesteps>=0

    #Get populations according to numerator and denominator
    x_pop = get_relevant_pop_name(data_name_x)
    y_pop = get_relevant_pop_name(data_name_y)
    if x_pop != y_pop:
        print(f"WARNING: population for {data_name_x} and {data_name_y} do not match. This is not fatal, but confirm with yourself that this is desired.")
    
    #Load and process relevant data from files
    lower_timeseries_by_alg = {}
    middle_timeseries_by_alg = {} 
    upper_timeseries_by_alg = {} 
    for alg in algs:
        try:
            #Load file
            with open(f"project_modelling/pickled_results/{alg}.pickle", "rb") as f:
                loaded_data = pickle.load(f)
                numerator_timeseriess = loaded_data[data_name_x] #alg_timeseries = {(seed, parametersation):[timeseries]}
                denominator_timeseriess = loaded_data[data_name_y]
                numerator_pop_timeseriess = loaded_data[x_pop]
                denominator_pop_timeseriess = loaded_data[y_pop]

            #Filter for the simulation runs we have accepted for analysis
            if accepted_paramandseeds is None:
                accepted_paramandseeds = set(numerator_timeseriess.keys())
            else:
                accepted_paramandseeds = accepted_paramandseeds.intersection(set(numerator_timeseriess.keys()))


            #Preprocess loaded timeserieses for easy computation of mean/std over timepoints (turn into numpy array)
            numerator_timeseriess_array = []
            denominator_timeseriess_array = []
            numerator_pop_timeseriess_array = []
            denominator_pop_timeseriess_array = []
            for key in accepted_paramandseeds: #iterate over (seed, parametersation) pairs, as this plotting does not need them as it does not do paired comparisons
                numerator_timeseriess_array.append(numerator_timeseriess[key])
                denominator_timeseriess_array.append(denominator_timeseriess[key]) #timeseries with the same (seed, parameterisation) pair have corresponding positions in alg_timeseriess_array and pop_size_array
                numerator_pop_timeseriess_array.append(numerator_pop_timeseriess[key])
                denominator_pop_timeseriess_array.append(denominator_pop_timeseriess[key])

            numerator_timeseriess_array = np.array(numerator_timeseriess_array) #shape (#timeseries, #timepoints in each timeseries)
            denominator_timeseriess_array = np.array(denominator_timeseriess_array)
            numerator_pop_timeseriess_array = np.array(numerator_pop_timeseriess_array)
            denominator_pop_timeseriess_array = np.array(denominator_pop_timeseriess_array)
            n,T = numerator_timeseriess_array.shape
            #print(n)

            if normalise_per_100k:
                numerator_timeseriess_array = np.divide(numerator_timeseriess_array, numerator_pop_timeseriess_array)
                denominator_timeseriess_array = np.divide(denominator_timeseriess_array, denominator_pop_timeseriess_array)


            ratio_timeseriess_array = np.divide(numerator_timeseriess_array, denominator_timeseriess_array)


            #compute lb, m, ub to be the timeseries of lower bounds, middles, and upper bounds respectively for this alg
            if show_quartiles:
                lb, m, ub = [],[],[]
                lb = list(np.percentile(ratio_timeseriess_array, 25, axis=0))
                ub = list(np.percentile(ratio_timeseriess_array, 75, axis=0))
                m = list(np.percentile(ratio_timeseriess_array, 50, axis=0))
            else: 
                #Compute means, stds
                means = np.mean(ratio_timeseriess_array, axis=0)
                stds = np.std(ratio_timeseriess_array, axis=0, ddof=1)

                #Compute confidence intervals (timepoint-wise) and add relevant timeseries to the dictionary to be plotted
                lb, ub = [], []; m = list(means)
                for t in range(T):
                    ci = stats.t.interval(
                        1-sig_level,
                        df = n-1,
                        loc = means[t],
                        scale = stds[t]/np.sqrt(n)
                    )
                    lb.append(ci[0]); ub.append(ci[1])


            lower_timeseries_by_alg[alg] = lb
            middle_timeseries_by_alg[alg] = m
            upper_timeseries_by_alg[alg] = ub            
        except Exception as e:
            print(f"Unable to open and/or process file project_modelling/pickled_results/{alg}.pickle. Omitting from plot")
            print(e)
            algs.remove(alg)

    #Smooth
    if smoothing_kernel>1:
        for alg in algs:
            lower_timeseries_by_alg[alg] = smooth_list(lower_timeseries_by_alg[alg], smoothing_kernel)
            middle_timeseries_by_alg[alg] = smooth_list(middle_timeseries_by_alg[alg], smoothing_kernel)
            upper_timeseries_by_alg[alg] = smooth_list(upper_timeseries_by_alg[alg], smoothing_kernel)

    #Recirpocate if needed
    if reciprocate:
        for alg in algs:
            lower_timeseries_by_alg[alg] = 1/np.array(lower_timeseries_by_alg[alg])
            middle_timeseries_by_alg[alg] = 1/np.array(middle_timeseries_by_alg[alg])
            upper_timeseries_by_alg[alg] = 1/np.array(upper_timeseries_by_alg[alg])

    #Plot
    for alg in algs: #algs has had any elements removed for which we could not successfully load and process data
        T = len(lower_timeseries_by_alg[alg])
        middles = middle_timeseries_by_alg[alg][burnin_timesteps:T-burnout_timesteps]
        xs = range(len(middles))

        if show_normal_CI or show_quartiles:
            lowers = lower_timeseries_by_alg[alg][burnin_timesteps:T-burnout_timesteps]
            uppers = upper_timeseries_by_alg[alg][burnin_timesteps:T-burnout_timesteps]
            ax.fill_between(xs, lowers, uppers, alpha=0.1, color=alg_colors[alg] if alg in alg_colors.keys() else None)
            ax.plot(xs, lowers, color=alg_colors[alg] if alg in alg_colors.keys() else None, linestyle='dotted', alpha=0.5)
            ax.plot(xs, uppers, color=alg_colors[alg] if alg in alg_colors.keys() else None, linestyle='dotted', alpha=0.5)
        ax.plot(xs, middles, color=alg_colors[alg] if alg in alg_colors.keys() else None, label= alg_labels[alg] if alg in alg_labels.keys() else alg) 
    return ax

def plot_paired_difference_tss(ax,
                               data_name, normalise_per_100k,
                               compared_alg, baseline_alg,
                               show_quartiles = False, show_normal_CI = False,
                               color=None, 
                               burnin_timesteps = 4*20, burnout_timesteps=4*5, smoothing_kernel=4,

                               ax_histogram = None, start_tp=None, end_tp=None,
                               compared_color=None, baseline_color=None,minimise=True,
                               accepted_paramandseeds = None):
    '''    
    Plots the difference in quantity over time between a baseline_alg and compared_alg. Finds difference by pairing timeserieses on parameterisation and seed.

    ax: The matplotlib axis to plot onto.
    data_name (str): the name of timeseries we will be returning paired differences of
    normalise_per_100k (bool): whether to deal with the timeseries in terms of raw numbers, or as rates
    compared_alg (str): the name of the algorithm from whose results we will be subtracting values to get the differences (X in X-Y)
    baseline_alg (str): the name of the algorithm whose results we use to subtract with (Y in X-Y)

    show_quartiles: if True, plots median curve at each timepoint bounded by LQ and UQ. 
    show_normal_CI: If True, plots mean and the t-test confidence interval around the mean.
        NOTE: show_quartiles and show_normal_CI cannot simultaneously be true

    color: matplotlib colour to use for the curve

    burnin_timesteps: the number of timesteps to ignore at the start of the plot, for burnin
    burnout_timesteps: the number of timesteps to ignore at the end of the plot, s.t. post-moving-average-smoothing we don't get an incorrect dropoff at the end of the plot (if 0, no burnout)
    smoothing_kernel: width (in timesteps) of moving average filter over timeseries

    ax_histogram: The axis to plot the histogram of sum of differences onto, if specified (if None, not doing this)
    start_tp: The starting timepoint if doing a histogram (for the sum)
    end_tp: The ending timepoint if doing a histogram (for the sum)
    
    compared_color: The matplotlib color to give the side of the histogram where the compared alg wins (i.e. when the baseline has a higher value iff {minimise}, else lower)
    baseline_color: The matplotlib color to give the side of the histogram where the baseline alg wins (i.e. when the compared has a higher value iff {minimise}, else lower)
    minimise: For specifying the colors, determines whether minimising {data_name} is a good thing (e.g. minimising cancers is a good thing)
        #NOTE: the above pack of three parameters need not be specified when doing a histogram, in which case the full histogram is coloured with {color}

    accepted_paramandseeds: If specified, defines the set of parameter-seed pairs which we use (all others are not used). Otherwise, plots all.

    Returns ax if ax_histogram is None, else (ax, ax_histogram)
    '''
    #Deal with parameters (assign defaults and check correctness)
    assert not (show_quartiles and show_normal_CI)
    assert data_name in data_names
        
    assert burnin_timesteps>=0
    assert burnout_timesteps>=0

    #Get paired differences for plotting
    difference_timeseriess, unmatched_compared, unmatched_baseline = get_paired_difference_tss(data_name, normalise_per_100k, compared_alg, baseline_alg)

    #Plot warnings for any unmatched
    if len(unmatched_compared) > 0:
        if len(unmatched_baseline) > 0:
            print("Unmatched algs in both directions.")
            print(f"\t Unmatched baseline: {unmatched_baseline}")
            print(f"\t Unmatched compared: {unmatched_compared}")
        else:
            print("Unmatched algs in one direction.")
            print(f"\t Unmatched compared: {unmatched_compared}")
    elif len(unmatched_baseline) > 0:
        print("Unmatched algs in one direction.")
        print(f"\t Unmatched baseline: {unmatched_baseline}")
    else:
        print("Fully matched.")

    #Filter for the simulation runs we have accepted for analysis
    if accepted_paramandseeds is None:
        accepted_paramandseeds = set(difference_timeseriess.keys())
    else:
        accepted_paramandseeds = accepted_paramandseeds.intersection(set(difference_timeseriess.keys()))

    #Turn the paired difference dictionary of timeseriess to a 2D array
    difference_timeseriess_array = []
    for key in accepted_paramandseeds: #iterate over (seed, parametersation) pairs, as this plotting does not need them as it does not do paired comparisons
        difference_timeseriess_array.append(difference_timeseriess[key])
    difference_timeseriess_array = np.array(difference_timeseriess_array) #shape (#timeseries, #timepoints in each timeseries)
    n,T = difference_timeseriess_array.shape

    #Work out quartiles/means+normal CI
    if show_quartiles:
        lb, m, ub = [],[],[]
        lb = list(np.percentile(difference_timeseriess_array, 25, axis=0))
        ub = list(np.percentile(difference_timeseriess_array, 75, axis=0))
        m = list(np.percentile(difference_timeseriess_array, 50, axis=0))
    else: 
        #Compute means, stds
        means = np.mean(difference_timeseriess_array, axis=0)
        stds = np.std(difference_timeseriess_array, axis=0, ddof=1)

        #Compute confidence intervals (timepoint-wise) and add relevant timeseries to the dictionary to be plotted (this won't be plotted in the end unless we have show_normal_CI==True
        lb, ub = [], []; m = list(means)
        for t in range(T):
            ci = stats.t.interval(
                1-sig_level,
                df = n-1,
                loc = means[t],
                scale = stds[t]/np.sqrt(n)
            )
            lb.append(ci[0]); ub.append(ci[1])

    lower_timeseries_by_alg = lb 
    middle_timeseries_by_alg = m
    upper_timeseries_by_alg = ub       

    #Smooth
    if smoothing_kernel>1:
        lower_timeseries_by_alg = smooth_list(lower_timeseries_by_alg, smoothing_kernel)
        middle_timeseries_by_alg = smooth_list(middle_timeseries_by_alg, smoothing_kernel)
        upper_timeseries_by_alg = smooth_list(upper_timeseries_by_alg, smoothing_kernel)

    #Plot
    T = len(middle_timeseries_by_alg)
    middles = middle_timeseries_by_alg[burnin_timesteps:T-burnout_timesteps]
    xs = range(len(middles))

    if show_normal_CI or show_quartiles:
        lowers = lower_timeseries_by_alg[burnin_timesteps:T-burnout_timesteps]
        uppers = upper_timeseries_by_alg[burnin_timesteps:T-burnout_timesteps]
        ax.fill_between(xs, lowers, uppers, alpha=0.1, color=color)
        ax.plot(xs, lowers, color=color, linestyle='dotted', alpha=0.5)
        ax.plot(xs, uppers, color=color, linestyle='dotted', alpha=0.5)
    ax.plot(xs, middles, color=color) 

    #Do histogram plotting, if relevant
    if ax_histogram is not None:

        total_diffs, unpairedcompared, unpairedbaseline = get_total_diffs(data_name, compared_alg, baseline_alg, 
                                                    start_tp, end_tp, normalise_per_100k) 
        if len(unpairedcompared)>0 or len(unpairedbaseline)>0:
            print(f"Failed to pair some of {compared_alg} and {baseline_alg}'s runs. {len(total_diffs)} runs were still paired successfully between the algorithms.")
        
        if compared_color is None:
            ax_histogram.hist(total_diffs, bins=12, density=True, color='deepskyblue') 
        else:
            #If we have specified colours for our histogram, use them
            _, hist_bins, hist_patches = ax_histogram.hist(total_diffs, bins=12, density=True, edgecolor='white', lw=0.5)
            for hist_patch_i in range(len(hist_patches)):
                #If the bin's left edge is on the left side of the y axis, that means we are talking of COMPARED-BASELINE<0, which means COMPARED<BASELINE, which means 'compared wins' iff {minimise}
                bin_left = hist_bins[hist_patch_i]
                bin_right = hist_bins[hist_patch_i+1]
                if bin_left+bin_right<0: #NOTE: this always colours a bar by the side most of its weight is on -this works as long as there is not a lot of weight exactly at 0 (at which point the colouring will be biased towards the algorithm on the right). For differing algorithms, this assumption should be OK in practice.
                    hist_patches[hist_patch_i].set_facecolor(compared_color if minimise else baseline_color)
                else: 
                    hist_patches[hist_patch_i].set_facecolor(baseline_color if minimise else compared_color)

        histogram_height = np.max(np.histogram(total_diffs, bins=12, density=True)[0])
        ax_histogram.vlines(0,0,histogram_height, colors='black', linewidth=1)

        ax.hlines(0.000002, min(total_diffs), max(total_diffs), colors='black', linewidth=1)
        ax.set_xlim(xmin=min(total_diffs), xmax=max(total_diffs))

        return (ax, ax_histogram)
    else:
        return ax

def plot_sum_barchart(ax, bar_colors, line_colors,
                            data_name, start_tp = 0, end_tp=0, 
                            normalise_per_100k=False, algs=[], 
                     xs=None, width=0.8,
                      hatch=None,
                      accepted_paramandseeds = None,
                      denominator_data_name = None):
    """
    As get_simple_totals, but then takes the totals and plots them as bars to {ax}. Bar heights are medians and upper and lower quartiles indicated by superimposed error bars.
    Bar positions given by xs, widths by {width}.
    Bar colors given by bar_colors, while colours for any lines on the bars given by line_colors. Hatching pattern given by hatch.
    
    accepted_paramandseeds: If specified, defines the set of parameter-seed pairs which we use (all others are not used). Otherwise, plots all.
    denominator_data_name: If specified, each bar is sum(data_name in specified time range)/sum(denominator_data_name in specified time range)
    """

    #Get totals
    totals_by_alg = get_simple_totals(data_name, start_tp, end_tp, normalise_per_100k, algs, accepted_paramandseeds)

    #Do dividing iff needed
    if denominator_data_name is not None:
        denominator_totals_by_alg = get_simple_totals(denominator_data_name, start_tp, end_tp, normalise_per_100k, algs, accepted_paramandseeds)
        for alg in algs:
            for i in range(len(totals_by_alg[alg])):
                totals_by_alg[alg][i] = totals_by_alg[alg][i] / denominator_totals_by_alg[alg][i] #we can do this as get_simple_totals only deals in arrays and lists (which conserves order) and always iterates through (seed,param) pairs in whatever way a dictionary is to iterate through them. Although that type need not conserve order, we can assume that in the miliseconds between loading the two sums, there is no reimplementarion of this function and can assume the function is udnerlying deterministic (TODO: this is not the best coding practice though, so perhaps should try and order the param_seed paris and then this is all fine)

    #Get values to be plotted for each alg (ordered according to ordering defined in {algs})
    LQs = [np.percentile(totals_by_alg[alg], 25) for alg in algs]
    medians = [np.median(totals_by_alg[alg]) for alg in algs]
    UQs = [np.percentile(totals_by_alg[alg], 75) for alg in algs]
    print(medians)

    #Turn colors into lists with ordering to match {algs}
    bar_colors = [bar_colors[alg] for alg in algs]
    line_colors = [line_colors[alg] for alg in algs]

    #Sort out x axis
    if xs is None:
        xs = list(range(len(algs)))
    ax.set_xticks(xs)
    ax.set_xticklabels(algs)

    #Plot
    ax.bar(xs if xs is not None else range(len(algs)),
            medians, width=width, color=bar_colors, edgecolor=line_colors, hatch=hatch)
    for i in range(len(LQs)):
        ax.errorbar([xs[i]], [medians[i]], yerr=([medians[i] - LQs[i]], [UQs[i]- medians[i]]), capsize=3, color='black')

