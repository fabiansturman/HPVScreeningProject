def run_sim_and_save_raw_result(provided_base_pars, seed:int,
                                final_cal_data, par_labels,
                                alg_name
                                ):
    """
    Runs a single HPVsim simulation with {base_pars} and RNG seed {seed}, over all parameterisations defined in {(final_cal_data, par_labels)}, and saving into pickle file f"project_modelling/pickled_results/{alg_name}.pickle".

    base_pars: full parameterisation of HPVsim excluding calibrated parameters - INCLUDING the interventions we are passing to the model; {base_pars} defines the non-calibrated parameters of our model including fully specifying the screening algorithm we are modelling
    seed: RNG seed for simulation
    final_cal_data: a list of parameter tuples [(v11,v12,...,v1p),...,(vn1,vn2,...,vnp)] where there are p calibrated parameters and n parameterisations
    par_labels: the internal HPVsim name for each of the p calibrated parameters, corresponding to the tuple orderings in {final_cal_data}
    alg_name: the name of the algorithm represented by {base_pars}; raw results from the simulation run will be saved to f"project_modelling/pickled_results/{alg_name}.pickle"
    """
    num_params = len(final_cal_data) #number of parameterisations which make up the ensemble model we are using
    for i in tqdm(range(num_params)):
        cal_params = final_cal_data[i][0] #specific parametersation of this iteration (note final_cal_data[i] is a tuple (parameterisation tuple, GOF, order statistic of GOF within the calibration that generated it, ID of calibration where the parameterisation was sampled ))
